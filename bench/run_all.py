"""Run all performance benchmarks and write bench/RESULTS.md.

  export SNOW_CONNECTION=<connection> DEMO_USER=<enrolled user>
  python3 bench/run_all.py                 # everything that runs unattended
  python3 bench/run_all.py opt2 opt2c      # only some
  python3 bench/run_all.py --report        # rebuild RESULTS.md from bench/results/*.json

Each benchmark runs in its option's own pixi environment. Needs: Docker lake up (opt1-tunnel: pixi run setup),
TOTP enrolment for DEMO_USER (opt2-keybroker: pixi run enroll), and for opt1b the Code Bundle
(opt1-tunnel/snowflake/21_code_bundle.sql).
"""
from __future__ import annotations

import json
import os
import subprocess
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RES = ROOT / "bench" / "results"

# name -> (pixi project dir, script)
BENCHES = {
    "snowflake": ("opt2c-device-flow", "b_snowflake.py"),
    "opt1": ("opt1-tunnel", "b_opt1.py"),
    "opt1b": ("opt1-tunnel", "b_opt1b.py"),
    "opt2": ("opt2-keybroker", "b_opt2.py"),
    "opt2c": ("opt2c-device-flow", "b_opt2c.py"),
    "opt2d": ("opt2c-device-flow", "b_opt2d.py"),
    "opt3": ("opt3-local-join", "b_opt3.py"),
    "opt4": ("opt4-client-decrypt", "b_opt4.py"),
    "he": ("bonus-homomorphic", "b_he.py"),
}


def run(name: str) -> bool:
    proj, script = BENCHES[name]
    log = RES / f"{name}.log"
    RES.mkdir(parents=True, exist_ok=True)
    t = time.time()
    print(f"== {name:9s} ({proj}) ...", end=" ", flush=True)
    with open(log, "w") as f:
        r = subprocess.run(["pixi", "run", "-q", "python", f"../bench/{script}"], cwd=ROOT / proj,
                           stdout=f, stderr=subprocess.STDOUT, stdin=subprocess.DEVNULL, env=os.environ.copy())
    print(f"{'ok' if r.returncode == 0 else 'FAILED (see ' + str(log.relative_to(ROOT)) + ')'} "
          f"in {time.time() - t:.0f} s")
    return r.returncode == 0


# ---------------------------------------------------------------------------------------------- report
def load(name: str) -> dict:
    p = RES / f"{name}.json"
    return json.loads(p.read_text()) if p.exists() else {}


def ms(v) -> str:
    if v is None:
        return "–"
    return f"{v / 1000:.1f} s" if v >= 1000 else f"{round(v)} ms"


def row(option, workload, d, where, note=""):
    if not d:
        return f"| {option} | {workload} | – | – | – | {where} | not run |"
    w = d.get("wall") or d.get("end_to_end") or d.get("query") or {}
    first = d.get("first_ms")
    return f"| {option} | {workload} | **{ms(w.get('p50'))}** | {ms(w.get('p95'))} | {ms(first)} | {where} | {note} |"


