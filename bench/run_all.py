def main(argv: list[str]) -> int:
    if "--report" not in argv:
        names = [a for a in argv if not a.startswith("-")] or [n for n in BENCHES if n != "opt1b"]
        ok = all([run(n) for n in names])
        if not ok:
            print("some benchmarks failed – the report shows the last successful result for each")
    (ROOT / "bench" / "RESULTS.md").write_text(report())
    print(f"wrote {(ROOT / 'bench' / 'RESULTS.md').relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
