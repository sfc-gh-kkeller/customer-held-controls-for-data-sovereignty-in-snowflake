-- Option 3 – split storage: ONLY non-sensitive data lives in Snowflake.
USE ROLE ACCOUNTADMIN;
CREATE SCHEMA IF NOT EXISTS SOVEREIGNTY_DEMO.OPT3_SPLIT;
CREATE ROLE IF NOT EXISTS SOV_SPLIT_ROLE;
SET me = CURRENT_USER();
GRANT ROLE SOV_SPLIT_ROLE TO USER IDENTIFIER($me);
GRANT USAGE ON DATABASE SOVEREIGNTY_DEMO TO ROLE SOV_SPLIT_ROLE;
GRANT USAGE ON WAREHOUSE SOV_WH TO ROLE SOV_SPLIT_ROLE;
GRANT OWNERSHIP ON SCHEMA SOVEREIGNTY_DEMO.OPT3_SPLIT TO ROLE SOV_SPLIT_ROLE COPY CURRENT GRANTS;

USE ROLE SOV_SPLIT_ROLE;
USE SCHEMA SOVEREIGNTY_DEMO.OPT3_SPLIT;
CREATE TABLE IF NOT EXISTS EMPLOYEES_PUBLIC (
  employee_id INT, department STRING, country STRING, hire_year INT, level INT);

-- Optional write-back target: only k-anonymous aggregates computed on-prem come back
CREATE TABLE IF NOT EXISTS SALARY_BANDS_AGG (
  department STRING, country STRING, headcount INT, avg_salary NUMBER(12,0),
  p50_salary NUMBER(12,0), computed_at TIMESTAMP_TZ, k_threshold INT);
