-- ============================================================================
-- Option 1 – On-demand tunnel: prerequisites (run as ACCOUNTADMIN)
-- Hardened replacement for prerequisites.sql
--   snow sql -c <connection> -f snowflake/00_prereqs.sql
-- Run through deploy.sh, which sets the handshake secret and fills <% ips %> with the agent's
-- egress IP(s) (ONPREM_IP, comma-separated; defaults to the IP deploy.sh runs from).
-- ============================================================================
USE ROLE ACCOUNTADMIN;

CREATE DATABASE IF NOT EXISTS SOVEREIGNTY_DEMO;
CREATE SCHEMA   IF NOT EXISTS SOVEREIGNTY_DEMO.OPT1_TUNNEL;

CREATE ROLE IF NOT EXISTS SOV_TUNNEL_ROLE;
GRANT ROLE SOV_TUNNEL_ROLE TO ROLE SYSADMIN;
SET me = CURRENT_USER();
GRANT ROLE SOV_TUNNEL_ROLE TO USER IDENTIFIER($me);

CREATE WAREHOUSE IF NOT EXISTS SOV_WH WAREHOUSE_SIZE = XSMALL AUTO_SUSPEND = 60 AUTO_RESUME = TRUE;
GRANT USAGE ON WAREHOUSE SOV_WH TO ROLE SOV_TUNNEL_ROLE;

GRANT USAGE ON DATABASE SOVEREIGNTY_DEMO TO ROLE SOV_TUNNEL_ROLE;
GRANT OWNERSHIP ON SCHEMA SOVEREIGNTY_DEMO.OPT1_TUNNEL TO ROLE SOV_TUNNEL_ROLE COPY CURRENT GRANTS;

-- Small pool that suspends quickly: the tunnel is not meant to be "always on"
CREATE COMPUTE POOL IF NOT EXISTS SOV_TUNNEL_POOL
  MIN_NODES = 1 MAX_NODES = 1
  INSTANCE_FAMILY = CPU_X64_XS
  AUTO_RESUME = TRUE
  AUTO_SUSPEND_SECS = 600;
GRANT USAGE, OPERATE, MONITOR ON COMPUTE POOL SOV_TUNNEL_POOL TO ROLE SOV_TUNNEL_ROLE;
GRANT BIND SERVICE ENDPOINT ON ACCOUNT TO ROLE SOV_TUNNEL_ROLE;

-- Hardening: egress only to the DuckDB extension host (original allowed 0.0.0.0)
CREATE OR REPLACE NETWORK RULE SOVEREIGNTY_DEMO.OPT1_TUNNEL.DUCKDB_EXT_RULE
  MODE = EGRESS TYPE = HOST_PORT
  VALUE_LIST = ('extensions.duckdb.org:443', 'extensions.duckdb.org:80');
CREATE OR REPLACE EXTERNAL ACCESS INTEGRATION SOV_DUCKDB_EAI
  ALLOWED_NETWORK_RULES = (SOVEREIGNTY_DEMO.OPT1_TUNNEL.DUCKDB_EXT_RULE)
  ENABLED = TRUE;
GRANT USAGE ON INTEGRATION SOV_DUCKDB_EAI TO ROLE SOV_TUNNEL_ROLE;

-- On-prem agent identity: service user, role-restricted PAT (created by deploy.sh),
-- network policy that only admits the agent's egress IP
CREATE OR REPLACE NETWORK RULE SOVEREIGNTY_DEMO.OPT1_TUNNEL.ONPREM_EGRESS_IP
  MODE = INGRESS TYPE = IPV4 VALUE_LIST = (<% ips %>);
CREATE NETWORK POLICY IF NOT EXISTS SOV_TUNNEL_AGENT_NP
  ALLOWED_NETWORK_RULE_LIST = ('SOVEREIGNTY_DEMO.OPT1_TUNNEL.ONPREM_EGRESS_IP');
CREATE USER IF NOT EXISTS SOV_TUNNEL_AGENT TYPE = SERVICE DEFAULT_ROLE = SOV_TUNNEL_ROLE
  DEFAULT_WAREHOUSE = SOV_WH COMMENT = 'on-prem tunnel agent (Option 1)';
ALTER USER SOV_TUNNEL_AGENT SET NETWORK_POLICY = SOV_TUNNEL_AGENT_NP;
GRANT ROLE SOV_TUNNEL_ROLE TO USER SOV_TUNNEL_AGENT;

USE ROLE SOV_TUNNEL_ROLE;
USE SCHEMA SOVEREIGNTY_DEMO.OPT1_TUNNEL;
CREATE IMAGE REPOSITORY IF NOT EXISTS TUNNEL_IMAGES;

-- Hardening: the handshake secret is a Snowflake SECRET, not a hard-coded default
CREATE OR REPLACE SECRET TUNNEL_HANDSHAKE_SECRET
  TYPE = GENERIC_STRING SECRET_STRING = $handshake_secret;

SHOW IMAGE REPOSITORIES IN SCHEMA SOVEREIGNTY_DEMO.OPT1_TUNNEL;
